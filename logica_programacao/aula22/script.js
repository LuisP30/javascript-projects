/*
Operadores lógicos

&& -> AND -> E
|| -> OR -> OU
! -> NOT -> NÃO

*/
console.log(true && false) // AND Necessita que todas as condições sejam verdadeiras para ser verdadeiro
console.log(true || false) // OR Necessita que apenas uma condição seja verdadeira para ser verdadeiro
console.log(!true) // NOT inverte o resultado de uma expressão
